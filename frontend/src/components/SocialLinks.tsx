const ORDER = ["facebook", "instagram", "tiktok", "youtube", "linkedin", "x"];

/** Only real http(s) links are shown. */
export function socialEntries(links: unknown): [string, string][] {
  const obj = links && typeof links === "object" ? (links as Record<string, unknown>) : {};
  return ORDER.filter((k) => typeof obj[k] === "string" && /^https?:\/\//.test(obj[k] as string)).map((k) => [k, obj[k] as string]);
}

export function SocialLinks({ links, tone = "dark" }: { links: unknown; tone?: "dark" | "light" }) {
  const entries = socialEntries(links);
  if (!entries.length) return null;
  const style =
    tone === "dark"
      ? "bg-white/10 text-white hover:bg-accent-500 hover:text-brand-950"
      : "bg-brand-100 text-brand-800 hover:bg-brand-800 hover:text-white";
  return (
    <ul className="flex flex-wrap gap-3">
      {entries.map(([key, url]) => (
        <li key={key}>
          <a
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`Chase Care Services on ${NETWORKS[key].label} (opens in a new tab)`}
            title={NETWORKS[key].label}
            className={`flex h-11 w-11 items-center justify-center rounded-full transition-colors ${style}`}
          >
            <svg aria-hidden="true" viewBox="0 0 24 24" className="h-5 w-5">
              {NETWORKS[key].icon}
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
